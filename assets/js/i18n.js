/* Tiny i18n helper shared by all scripts. */
window.t = function (key, vars) {
  var lang = document.documentElement.lang === "mn" ? "mn" : "en";
  var s = (window.I18N[lang] && window.I18N[lang][key]) || window.I18N.en[key] || key;
  if (vars) for (var k in vars) s = s.replace("{" + k + "}", vars[k]);
  return s;
};
window.pick = function (v) {
  if (v == null || typeof v !== "object") return v;
  return document.documentElement.lang === "mn" ? v.mn : v.en;
};
